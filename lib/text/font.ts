/** Block letters for a line of text, or null if it has characters the font lacks or is too wide. */
export function blockText(text: string, maxWidth: number): string[] | null {
  const chars = [...text.toUpperCase()];
  if (chars.some((c) => !G[c])) return null;
  const rows = [0, 1, 2, 3, 4].map((r) => chars.map((c) => G[c][r]).join(" "));
  return rows[0].length <= maxWidth ? rows : null;
}
